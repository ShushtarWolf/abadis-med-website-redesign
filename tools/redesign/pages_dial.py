"""Calculator = ShushtarWolf's «دایال عملی» (site/dial-practical/, main) — reused verbatim, not modified.
Its inline <style>/<script> + common/abadis-common.{css,js} are copied into site/assets/dial/, global rules
(*, html, main#main) are scoped to .dp-embed so the same calculator can sit inside /calculator/ and the home page."""
import re
from lib import SITE
from layout import page

SRC = SITE / 'dial-practical'
OUT = SITE / 'assets' / 'dial'
DESC = 'محاسبه‌گر صرفه‌جویی آبادیس: صرفه‌جویی در مصرف آب، هزینه شست‌وشو و ضدعفونی و زمان کادر درمان.'

def _parts():
    h = (SRC / 'index.html').read_text(encoding='utf-8')
    css = re.search(r'<style[^>]*>(.*?)</style>', h, re.S).group(1)
    js = [b for b in re.findall(r'<script>(.*?)</script>', h, re.S) if 'Abadis' in b][0]
    main = h[h.index('<main'):h.index('</main>')]
    sec = lambda sid: re.search(r'(<section class="calc dial-sec" id="%s".*?</section>)\s*(?=<section|\Z)' % sid, main + '<section', re.S).group(1)
    intro = re.search(r'<section class="intro".*?</section>', main, re.S).group(0)
    cta = re.search(r'<section class="cta-band">.*?</section>', main, re.S).group(0)
    return css, js, intro, sec('calc1'), sec('calc2'), cta

def _assets(css, js):
    OUT.mkdir(parents=True, exist_ok=True)
    common = (SRC / 'common' / 'abadis-common.css').read_text(encoding='utf-8')
    common = common.replace('* { box-sizing: border-box; margin: 0; padding: 0; }', '.dp-embed, .dp-embed * { box-sizing: border-box; }\n.dp-embed h1, .dp-embed h2, .dp-embed h3, .dp-embed p { margin: 0; }')
    common = common.replace('html { scroll-behavior: smooth; }', '')
    css = re.sub(r'\n\s*main#main \{[^}]*\}', '', css)
    css = re.sub(r'\n\s*\.intro \{ padding-top: 120px; \}', '\n    .dp-page .intro { padding-top: 120px; }', css)
    (OUT / 'dial.css').write_text('/* generated by tools/redesign/pages_dial.py from site/dial-practical/ (ShushtarWolf) */\n' + common + '\n' + css, encoding='utf-8')
    (OUT / 'abadis-common.js').write_text((SRC / 'common' / 'abadis-common.js').read_text(encoding='utf-8'), encoding='utf-8')
    (OUT / 'dial-practical.js').write_text('/* generated from site/dial-practical/index.html inline script (ShushtarWolf) */\n' + js, encoding='utf-8')

def scripts(p):
    return f'<script src="{p}assets/dial/abadis-common.js"></script>\n<script src="{p}assets/dial/dial-practical.js" defer></script>\n'

def head(p):
    return f'<link rel="stylesheet" href="{p}assets/dial/dial.css">'

