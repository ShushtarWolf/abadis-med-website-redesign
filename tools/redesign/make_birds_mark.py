"""Assets for the hero-test/birds page: the teal logo mark (cropped from abadis-logo-teal.png) and
~110 bird landing points sampled from its alpha (thick "AS" strokes + the ring band).

    python3 tools/redesign/make_birds_mark.py
"""
import json
import math
import os
import random
from PIL import Image, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
LOGO = os.path.join(ROOT, 'site', 'assets', 'img', 'abadis-logo-teal.png')
OUT = os.path.join(ROOT, 'site', 'hero-test', 'birds')
N_STROKE, N_RING = 74, 38


def main():
    os.makedirs(OUT, exist_ok=True)
    logo = Image.open(LOGO).convert('RGBA')
    mark = logo.crop((360, 0, 658, 309))
    w, h = mark.size
    mark.save(os.path.join(OUT, 'mark.png'), optimize=True)
    a = mark.split()[3]
    # thick strokes only: erode away the thin ring lettering / circle line
    thick = a.point(lambda v: 255 if v > 140 else 0).filter(ImageFilter.MinFilter(5))
    tp = thick.load()
    cand = [(x, y) for y in range(0, h, 2) for x in range(0, w, 2) if tp[x, y]]
    rnd = random.Random(7)
    rnd.shuffle(cand)
    def poisson(dist):
        out = []
        for p in cand:
            if all((p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2 >= dist * dist for q in out):
                out.append(p)
        return out

    lo, hi = 4.0, 40.0                      # even spacing along the strokes: find the spacing giving N_STROKE
    for _ in range(18):
        mid = (lo + hi) / 2
        if len(poisson(mid)) > N_STROKE: lo = mid
        else: hi = mid
    pts = poisson(hi)[:N_STROKE]
    # ring band (lettering + outer circle) as an even circle of birds
    cx, cy = w / 2.0, h / 2.0 + 2
    r = min(w, h) * 0.455
    for i in range(N_RING):
        t = 2 * math.pi * i / N_RING + 0.08
        pts.append((cx + r * math.cos(t), cy + r * math.sin(t)))
    norm = [[round(x / w, 4), round(y / h, 4)] for x, y in pts]
    with open(os.path.join(OUT, 'mark-points.js'), 'w') as f:
        f.write('/* generated by tools/redesign/make_birds_mark.py */\n')
        f.write('window.ABADIS_MARK = ' + json.dumps({'w': w, 'h': h, 'pts': norm}, separators=(',', ':')) + ';\n')
    print(len(norm), 'points;', os.path.getsize(os.path.join(OUT, 'mark.png')), 'bytes mark.png')


if __name__ == '__main__':
    main()
