def home_section():
    css, js, intro, c1, c2, cta = _parts()
    _assets(css, js)
    fix = lambda h: h.replace('href="../contact/" target="_blank" rel="noopener"', 'href="contact/"').replace('href="../contact/"', 'href="contact/"')
    intro, c1, c2 = fix(intro), fix(c1), fix(c2)
    return f'''  <section class="section section--alt home-dial" id="calculator">
    <div class="dp-embed">
      {intro.replace('<section class="intro" id="top">', '<section class="intro home-dial-intro">').replace('<h1>', '<h2>').replace('</h1>', '</h2>')}
      {c1}
      {c2}
      {METHOD_FA}
      <p class="home-dial-more"><a class="more-link" href="calculator/">صفحهٔ محاسبه‌گر ←</a></p>
    </div>
  </section>'''

def build(write):
    import pages_calculator
    css, js, intro, c1, c2, cta = _parts()
    _assets(css, js)
    p = '../'
    cta = cta.replace('href="../contact/" target="_blank" rel="noopener"', 'href="../contact/"')
    main = f'<div class="dp-embed dp-page">\n{intro}\n{c1}\n{c2}\n{METHOD_FA}\n{cta}\n{pages_calculator.switcher(p, "")}\n</div>'
    write('calculator/index.html', page(p, 'calculator', 'محاسبه‌گر صرفه‌جویی', DESC, main,
          extra_head=head(p) + f'\n<link rel="stylesheet" href="calc-page.css">', scripts=scripts(p)))
